import pandas as pd
import matplotlib.pyplot as plt

# Load the data
data = pd.read_csv('resources/input/data/20150576_data5.csv')

# Figure 3: Trend in the Fertility Rate and Child Sex Ratio in India
plt.figure(figsize=(10, 6))
plt.plot(data['year'], data['ideal'], label='Total fertility rate', marker='o')
plt.plot(data['year'], data['csr'], label='Child sex ratio', marker='s')
plt.xlabel('Year')
plt.ylabel('Rate/Ratio')
plt.title('Trend in the Fertility Rate and Child Sex Ratio in India')
plt.legend()
plt.xticks(rotation=45)
plt.grid(True)
plt.tight_layout()
plt.show()

# Figure 4: How Much of the Sex Ratio Trend Can Fertility Decline Explain? (Method 1)
plt.figure(figsize=(10, 6))
plt.plot(data['year'], data['csr'], label='Actual child sex ratio', marker='o')
plt.plot(data['year'], data['sr_project1'], label='Estimated child sex ratio based on desired fertility', marker='x')
plt.plot(data['year'], data['ideal'], label='Desired fertility', linestyle='--')
plt.xlabel('Year')
plt.ylabel('Ratio/Rate')
plt.title('Method 1: Fertility Decline and Sex Ratio Trend')
plt.legend()
plt.xticks(rotation=45)
plt.grid(True)
plt.tight_layout()
plt.show()

# Figure 5: How Much of the Sex Ratio Trend Can Fertility Decline Explain? (Method 2)
plt.figure(figsize=(10, 6))
plt.subplot(2, 1, 1)
plt.plot(data['year'], data['frac_noboy_women'], label='Percent with no son within desired fertility', marker='x')
plt.plot(data['year'], data['ssa'], label='Percent using sex-selective abortion if no boy', marker='o')
plt.ylabel('Percent')
plt.title('Panel A: Percent using sex-selective abortion')
plt.legend()
plt.xticks(rotation=45)
plt.grid(True)

plt.subplot(2, 1, 2)
plt.plot(data['year'], data['csr'], label='Child sex ratio', marker='o')
plt.plot(data['year'], data['pct_boys'], label='Projected sex ratio holding constant desired fertility', marker='x')
plt.xlabel('Year')
plt.ylabel('Sex Ratio')
plt.title('Panel B: Sex Ratio Projection')
plt.legend()
plt.xticks(rotation=45)
plt.grid(True)
plt.tight_layout()
plt.show()